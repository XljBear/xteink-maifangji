"""把 src/ 打成一个 index.lua（设备上的 Lua 宿主不给包里的文件用 require）。

  python -I bundle.py

src/fangchan_data.lua（商品、房源、新闻）和 src/fangchan_game.lua（规则）先进一个模块表，
src/ui.lua（那一屏）接在最后。改 src/，别改生成的 index.lua。
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'src')

PRELUDE = r"""-- GENERATED by bundle.py from src/ -- edit those files, not this one.
-- 买房记 for XTOS Licorice：开局 2000 元，60 个回合，买卖八种货，赚够钱买一套房。
-- 每一步都自动存档。所有 ctx.* 都是方法：一律冒号调用。

-- 游戏用 os.time() 给骰子播种；宿主不一定有 os
local os = { time = function()
  local ok, t = pcall(function() return ctx.clock:millis() end)
  return (ok and tonumber(t)) or 0
end }

local __mods, __loaded = {}, {}
local function require(name)
  local v = __loaded[name]
  if v ~= nil then return v end
  local f = __mods[name]
  if not f then error('module not found: ' .. tostring(name)) end
  v = f()
  if v == nil then v = true end
  __loaded[name] = v
  return v
end

__mods['ffi/util'] = function()
  -- KOReader 的 template：%1 .. %9 换成后面的参数
  return { template = function(fmt, ...)
    local a = table.pack(...)
    return (tostring(fmt):gsub('%%(%d)', function(n)
      local v = a[tonumber(n)]
      if v == nil then return '%' .. n end
      return tostring(v)
    end))
  end }
end
"""


def module(name, path):
    body = open(path, encoding='utf-8').read().rstrip('\n')
    return f"\n__mods['{name}'] = function()\n{body}\nend\n"


def bundle():
    parts = [PRELUDE]
    for name in ('fangchan_data', 'fangchan_game'):
        parts.append(module(name, os.path.join(SRC, name + '.lua')))
    parts.append('\n' + open(os.path.join(SRC, 'ui.lua'), encoding='utf-8').read())
    out = os.path.join(HERE, 'index.lua')
    text = ''.join(parts)
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if text != old:
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'买房记: index.lua {len(text)} B ({"updated" if text != old else "unchanged"})')
    return out


if __name__ == '__main__':
    bundle()
